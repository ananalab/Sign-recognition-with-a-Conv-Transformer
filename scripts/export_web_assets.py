def landmarks_js() -> str:
    groups = [{"name": n, "source": s, "indices": list(i)} for n, s, i in lm.GROUPS]
    slices = {k: [v.start, v.stop] for k, v in lm.SLICES.items()}
    body = {
        "N_LANDMARKS": lm.N_LANDMARKS,
        "GROUPS": groups,
        "SLICES": slices,
        "POSE_POS": lm.POSE_POS,
        "MIRROR": lm.mirror_permutation(),
        "EDGES": [list(e) for e in lm.skeleton_edges()],
    }
    lines = ["// Generated by scripts/export_web_assets.py from src/signrec/landmarks.py."]
    for k, v in body.items():
        lines.append(f"export const {k} = {json.dumps(v)};")
    return "\n".join(lines) + "\n"


def _seq(rng: np.random.Generator, T: int) -> np.ndarray:
    seq = (0.5 + 0.08 * rng.standard_normal((T, lm.N_LANDMARKS, 3))).astype(np.float32)
    seq[:, lm.POSE_POS["l_shoulder"], :2] = [0.66, 0.62]
    seq[:, lm.POSE_POS["r_shoulder"], :2] = [0.34, 0.61]
    seq += 0.01 * np.cumsum(rng.standard_normal((T, 1, 3)), axis=0).astype(np.float32)
    return seq


def fixtures() -> list[dict]:
    rng = np.random.default_rng(42)
    cases = []

    def add(name: str, seq: np.ndarray, cfg: PreprocessConfig, y_scale: float = 1.0) -> None:
        x, m = preprocess(seq, cfg, y_scale=y_scale)
        cases.append(
            {
                "name": name,
                "cfg": cfg.to_dict(),
                "y_scale": y_scale,
                "shape": list(seq.shape),
                "seq": [None if np.isnan(v) else float(v) for v in seq.ravel()],
                "features": x.ravel().tolist(),
                "mask": m.astype(int).tolist(),
            }
        )

    base = PreprocessConfig()
    s = _seq(rng, 40)
    add("plain", s, base)
    add("webcam_aspect_4_3", s, base, y_scale=0.75)
    add("lsfb_aspect", s, base, y_scale=0.5625)
    s2 = _seq(rng, 37)
    s2[:, lm.SLICES["right_hand"]] = np.nan
    s2[:4, :42] = np.nan
    s2[-3:, :42] = np.nan
    s2[rng.random(s2.shape[:2]) < 0.05] = np.nan
    add("left_dominant_trim_nan", s2, base)
    add("mirrored", mirror(s2), base)
    s3 = _seq(rng, 25)
    s3[:, :42] = np.nan
    add("no_hands", s3, base)
    s4 = _seq(rng, 12)
    s4[:, lm.POSE_POS["l_shoulder"]] = np.nan
    add("no_shoulders_fallback", s4, base)
    add("single_frame", _seq(rng, 1), base)
    add("long", _seq(rng, 150), base)
    add("pad_mode", _seq(rng, 20), PreprocessConfig(length_mode="pad"))
    add("xyz_no_lips_T32", _seq(rng, 50),
        PreprocessConfig(T=32, use_z=True, parts=("left_hand", "right_hand", "pose")))  # fmt: skip
    return cases


